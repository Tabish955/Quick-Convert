# Generates the Phase 4 acceptance sample: a DOCX of approximately the requested size, built from
# generated chapters and a few incompressible images. Nothing binary is committed; the document is
# produced on demand with Pandoc, so no Word installation is required.
#
#   powershell -File tools\spike\Make-SampleDocx.ps1 -TargetMegabytes 5 -OutFile .\sample-5mb.docx
#
# Then convert it with the application and record the time, page count and output size in
# docs/PHASE_4_STATUS.md. Requires Pandoc (tools\pandoc\pandoc.exe or on PATH).

[CmdletBinding()]
param(
    [int]$TargetMegabytes = 5,
    [string]$OutFile = (Join-Path (Get-Location).Path "sample-5mb.docx"),
    [string]$WorkDir = (Join-Path $env:TEMP ("qc-sample-" + [Guid]::NewGuid().ToString("N"))),
    [int]$ChapterCount = 25
)

$ErrorActionPreference = "Stop"

function Find-Pandoc {
    $shipped = Join-Path $PSScriptRoot "..\pandoc\pandoc.exe"
    if (Test-Path $shipped) { return (Resolve-Path $shipped).Path }

    $command = Get-Command pandoc -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }

    throw "Pandoc not found. Run tools\Get-Pandoc.ps1 first, or put pandoc on PATH."
}

function New-NoiseBitmap {
    param(
        [string]$Path,
        [int]$Width,
        [int]$Height,
        [int]$Seed
    )

    # A 24 bit uncompressed BMP full of random bytes. Random data does not compress, so the file size
    # inside the DOCX stays predictable, and the image is large enough that dropping it is visible.
    $rowBytes = [int]([math]::Floor((($Width * 3) + 3) / 4) * 4)
    $pixelBytes = [int]($rowBytes * $Height)
    $fileSize = [int](54 + $pixelBytes)

    $pixels = New-Object byte[] $pixelBytes
    $random = New-Object System.Random($Seed)
    $random.NextBytes($pixels)

    $header = New-Object byte[] 54
    $header[0] = 0x42
    $header[1] = 0x4D
    [BitConverter]::GetBytes($fileSize).CopyTo($header, 2)
    [BitConverter]::GetBytes([int]54).CopyTo($header, 10)
    [BitConverter]::GetBytes([int]40).CopyTo($header, 14)
    [BitConverter]::GetBytes([int]$Width).CopyTo($header, 18)
    [BitConverter]::GetBytes([int]$Height).CopyTo($header, 22)
    [BitConverter]::GetBytes([int16]1).CopyTo($header, 26)
    [BitConverter]::GetBytes([int16]24).CopyTo($header, 28)
    [BitConverter]::GetBytes([int]$pixelBytes).CopyTo($header, 34)
    [BitConverter]::GetBytes([int]2835).CopyTo($header, 38)
    [BitConverter]::GetBytes([int]2835).CopyTo($header, 42)

    $stream = [System.IO.File]::Create($Path)
    try {
        $stream.Write($header, 0, $header.Length)
        $stream.Write($pixels, 0, $pixels.Length)
    }
    finally {
        $stream.Dispose()
    }

    return $fileSize
}

$pandoc = Find-Pandoc
Write-Host "Pandoc: $pandoc"

New-Item -ItemType Directory -Path $WorkDir -Force | Out-Null
Write-Host "Working directory: $WorkDir"

$targetBytes = $TargetMegabytes * 1MB
$imageWidth = 900
$imageHeight = 600
$imageCount = 3
$imagePlacements = @(3, 12, 21)

$imageBytes = 0
$imageNames = @()
for ($i = 1; $i -le $imageCount; $i++) {
    $name = "figure-{0}.bmp" -f $i
    $imageBytes += New-NoiseBitmap -Path (Join-Path $WorkDir $name) -Width $imageWidth -Height $imageHeight -Seed (1000 + $i)
    $imageNames += $name
}

# Leave room for the DOCX container and the XML around the text.
$textBudget = [int]([math]::Max(40000, $targetBytes - $imageBytes - 300KB))
$charsPerChapter = [int][math]::Ceiling($textBudget / $ChapterCount)

$sentences = @(
    "A file converter has one job, and it should do it without asking the user to think.",
    "The application reads the source file, writes a new one beside it, and reports progress while it works.",
    "Nothing leaves the machine, and no component contacts a server for any reason.",
    "When a conversion cannot be performed, the interface says why instead of failing silently.",
    "Long operations run in the background so the window stays responsive throughout.",
    "Every output name is unique, because overwriting a file is not a decision the tool should make on its own."
)

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("% Phase 4 acceptance sample")
$lines.Add("")
$lines.Add("Generated by tools/spike/Make-SampleDocx.ps1 for a target of $TargetMegabytes MB.")
$lines.Add("")

$imageIndex = 0
for ($chapter = 1; $chapter -le $ChapterCount; $chapter++) {
    $lines.Add("# Chapter $chapter")
    $lines.Add("")
    $lines.Add("This chapter exists to give the document realistic length and structure.")
    $lines.Add("")

    $written = 0
    $paragraph = 1
    while ($written -lt $charsPerChapter) {
        $lines.Add("## Section $chapter.$paragraph")
        $lines.Add("")
        $body = ($sentences * 3) -join " "
        $lines.Add($body)
        $lines.Add("")
        $written += $body.Length + 40
        $paragraph++
    }

    if ($imageIndex -lt $imageCount -and $chapter -eq $imagePlacements[$imageIndex]) {
        $lines.Add("![Figure $($imageIndex + 1)]($($imageNames[$imageIndex]))")
        $lines.Add("")
        $imageIndex++
    }
}

# Any image whose placement chapter exceeded the chapter count still lands in the document.
while ($imageIndex -lt $imageCount) {
    $lines.Add("![Figure $($imageIndex + 1)]($($imageNames[$imageIndex]))")
    $lines.Add("")
    $imageIndex++
}

$markdownPath = Join-Path $WorkDir "sample.md"
$encoding = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($markdownPath, ($lines -join "`r`n"), $encoding)

$outDirectory = Split-Path -Parent $OutFile
if ($outDirectory -and -not (Test-Path $outDirectory)) {
    New-Item -ItemType Directory -Path $outDirectory -Force | Out-Null
}

& $pandoc $markdownPath --from markdown --to docx --output $OutFile --resource-path $WorkDir
if ($LASTEXITCODE -ne 0) {
    throw "Pandoc exited with code $LASTEXITCODE"
}

$result = Get-Item $OutFile
Write-Host ""
Write-Host ("Sample written: {0}" -f $result.FullName)
Write-Host ("Size: {0:N0} bytes ({1:N2} MB)" -f $result.Length, ($result.Length / 1MB))
Write-Host ("Chapters: {0}, images: {1} ({2:N0} bytes of image data)" -f $ChapterCount, $imageCount, $imageBytes)
Write-Host "Convert it to PDF with the application, then confirm the images appear and record the numbers."
